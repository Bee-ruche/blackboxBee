int bee_answer(const u8 *in, usize n, u8 *out, usize *len)
{
    if (n <= 4 || n - 4 > BEE_OUT_MAX)
        return 1;

    u32 key = (u32)in[0] | ((u32)in[1] << 8)
              | ((u32)in[2] << 16) | ((u32)in[3] << 24);
    if (key == 0)
        return 1;

    usize payload_len = n - 4;
    usize padding = (8 - (payload_len & 7u)) & 7u;
    usize output_len = payload_len + padding;
    u8 chain[8];
    u32 round_keys[6];

    for (usize i = 0; i < 8; ++i)
        chain[i] = in[i & 3u];
    for (u32 round = 0; round < 6; ++round) {
        u32 shift = 1 + 5 * round;
        u32 rotated = (key << shift) | (key >> (32 - shift));
        round_keys[round] = rotated ^ (0x5a17c3e9u * (round + 1));
    }

    for (usize offset = 0; offset < output_len; offset += 8) {
        u8 block[8];
        for (usize i = 0; i < 8; ++i) {
            usize index = offset + i;
            u8 byte = index < payload_len ? in[4 + index] : (u8)(0xa0u | padding);
            block[i] = byte ^ chain[i];
        }

        for (u32 round = 0; round < 6; ++round) {
            u64 packed = 0;
            for (usize i = 0; i < 8; ++i) {
                u8 mask = (u8)(round_keys[round] >> (8 * (i & 3u)));
                packed |= (u64)substitution[block[i] ^ mask] << (8 * i);
            }
            u32 shift = 3 + 7 * round;
            packed = (packed << shift) | (packed >> (64 - shift));
            for (usize i = 0; i < 8; ++i)
                block[i] = (u8)(packed >> (8 * i));

            /* Mixing is in place, so wrapped indices see the updated bytes. */
            for (usize i = 0; i < 8; ++i)
                block[i] ^= block[(i + 3) & 7u];
        }

        for (usize i = 0; i < 8; ++i) {
            out[offset + i] = block[i];
            chain[i] = block[i];
        }
    }
    *len = output_len;
    return 0;
}
